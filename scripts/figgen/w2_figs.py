deg = [len(adjK[i]) for i in range(KN)]

def bfs_dist(s):
    dist = {s: 0}
    q = deque([s])
    while q:
        u = q.popleft()
        for v in adjK[u]:
            if v not in dist:
                dist[v] = dist[u] + 1
                q.append(v)
    return dist

clo = [ (KN - 1) / sum(bfs_dist(s).values()) for s in range(KN)]

# betweenness by path enumeration (BFS DAG counting)
btw = [0.0] * KN
for s in range(KN):
    dist = bfs_dist(s)
    sigma = {v: 0 for v in range(KN)}; sigma[s] = 1
    order = sorted(dist, key=dist.get)
    for u in order:
        for v in adjK[u]:
            if dist[v] == dist[u] + 1:
                sigma[v] += sigma[u]
    delta = {v: 0.0 for v in range(KN)}
    for u in reversed(order):
        for v in adjK[u]:
            if dist[v] == dist[u] + 1:
                delta[u] += sigma[u] / sigma[v] * (1 + delta[v])
        if u != s:
            btw[u] += delta[u]
btw = [b / 2 for b in btw]

eig = [1.0] * KN
for _ in range(300):
    nxt = [sum(eig[j] for j in adjK[i]) for i in range(KN)]
