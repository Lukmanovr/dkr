def radius(u):
    return 8 + 40 * math.sqrt(PR[u])


BOW_SIDE = {("V", "N3"): -1}   # -1 bows to the right of travel; default is left


def edge_path(u, v):
    # Quadratic arc from u's rim to just short of v's rim, bowed to the left of travel
    # so a pair of opposite links separates into two distinct arcs.
    (x1, y1), (x2, y2) = WPOS[u], WPOS[v]
    dx, dy = x2 - x1, y2 - y1
    L = math.hypot(dx, dy)
    ux, uy = dx / L, dy / L
    px, py = -uy, ux                      # left-hand normal
    bow = 0.13 * L * BOW_SIDE.get((u, v), 1)
    cx, cy = (x1 + x2) / 2 + px * bow, (y1 + y2) / 2 + py * bow
    # trim both ends so the arrowhead lands on the rim of v, not under the disc
    r1, r2 = radius(u) + 2, radius(v) + head_len(u, v) + 1
    # direction at the ends of the quadratic
    d1x, d1y = cx - x1, cy - y1
    l1 = math.hypot(d1x, d1y); d1x, d1y = d1x / l1, d1y / l1
    d2x, d2y = x2 - cx, y2 - cy
    l2 = math.hypot(d2x, d2y); d2x, d2y = d2x / l2, d2y / l2
    sx, sy = x1 + d1x * r1, y1 + d1y * r1
    ex, ey = x2 - d2x * r2, y2 - d2y * r2
    return f"M {sx:.1f} {sy:.1f} Q {cx:.1f} {cy:.1f} {ex:.1f} {ey:.1f}"


def edge_width(u, v):
    return 1.5 + 20 * FLOW[(u, v)]


def head_len(u, v):
    return max(11.0, 4.4 * edge_width(u, v))  # long head: the tip is an acute point


def head_half(u, v):
    return max(2.6, 0.8 * edge_width(u, v))   # narrow head: about a 20-degree tip


def marker_id(u, v):
    return f"w2h_{u}_{v}"


