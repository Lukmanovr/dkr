# ════════════════════════════════ PageRank hero ════════════════════════════
# A toy web where page Q has ONE inlink (from the giant hub) and page V has FOUR
# inlinks from leaf pages — and PageRank ranks Q above V. Quality beats quantity.
# Every edge is drawn with a width proportional to the mass it carries per step,
# β·r_u / d_out(u), so the argument is visible before the numbers are read: one fat
# link into Q, four hairlines into V. A ledger underneath stacks those arrivals.
WEB = {  # node -> outlinks
    "Hub": ["Q", "N1", "N2"],
    "N1": ["Hub"], "N2": ["Hub"], "N3": ["Hub"], "N4": ["Hub", "V"],
    "L1": ["V"], "L2": ["V"], "L3": ["V"],
    "Q": ["Hub"],
    "V": ["N3"],
}
NODES = list(WEB)
BETA = 0.85


def pagerank(web, beta=BETA, iters=200):
    nodes = list(web)
    n = len(nodes)
    pr = {u: 1 / n for u in nodes}
    for _ in range(iters):
        nxt = {u: (1 - beta) / n for u in nodes}
        for u, outs in web.items():
            share = beta * pr[u] / len(outs)
            for v in outs:
                nxt[v] += share
        pr = nxt
    return pr


PR = pagerank(WEB)
assert PR["Q"] > PR["V"], "the story requires PR(Q) > PR(V); adjust the toy web"
NPAGES = len(NODES)
TELEPORT = (1 - BETA) / NPAGES
FLOW = {(u, v): BETA * PR[u] / len(outs) for u, outs in WEB.items() for v in outs}
IN_Q = [(u, FLOW[(u, "Q")]) for u in NODES if "Q" in WEB[u]]
IN_V = [(u, FLOW[(u, "V")]) for u in NODES if "V" in WEB[u]]
assert abs(sum(f for _, f in IN_Q) + TELEPORT - PR["Q"]) < 1e-9
assert abs(sum(f for _, f in IN_V) + TELEPORT - PR["V"]) < 1e-9

