# Q15: one GCN propagation on the path 1–2–3, x = (1,0,0)
A = np.array([[0, 1, 0], [1, 0, 1], [0, 1, 0]], dtype=float)
At = A + np.eye(3)
d = At.sum(1)
Ahat = np.diag(d ** -0.5) @ At @ np.diag(d ** -0.5)
x = np.array([1.0, 0.0, 0.0])
out = Ahat @ x
assert np.allclose(out, [0.5, 1 / np.sqrt(6), 0.0]), f"Âx = {out}"
print(f"Q15 verified: Âx = (1/2, 1/√6, 0) ≈ ({out[0]:.3f}, {out[1]:.3f}, {out[2]:.3f})")

