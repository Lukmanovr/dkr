# ════════════════ Q6/Q17: two triangles vs one hexagon (WL-blind pair) ═════
def wl_hist(g, rounds=3):
    colors = {v: 0 for v in g}
    hists = []
    for _ in range(rounds):
        colors = {v: hash((colors[v], tuple(sorted(colors[u] for u in g[v])))) for v in g}
        hists.append(sorted(__import__("collections").Counter(colors.values()).values()))
    return hists


G_tri = nx.disjoint_union(nx.cycle_graph(3), nx.cycle_graph(3))
G_hex = nx.cycle_graph(6)
assert wl_hist(G_tri) == wl_hist(G_hex), "WL color histograms identical every round — the blind pair"
assert not nx.is_isomorphic(G_tri, G_hex), "…and yet the graphs are genuinely different"
print("Q6 verified: WL histograms equal for C3∪C3 vs C6 at every round; graphs non-isomorphic")

