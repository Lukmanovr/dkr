# — ComplEx panel (2,0): the same one-drawing grammar as its siblings — a unit
# circle showing h, t, and the conjugate flip t̄ that breaks the swap symmetry
ox = 392
p = [frame(ox, oy, "ComplEx", "Re⟨h, r, t̄⟩", "var(--dkr-blue, #0f8377)")]
