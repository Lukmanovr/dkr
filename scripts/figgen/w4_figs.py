for j, (m, color) in enumerate(MODELS):
    pat.append(f'  <text x="{X0 + CW * j + CW / 2}" y="{Y0 + 18}" text-anchor="middle" font-family="{SANS}" font-size="13.5" font-weight="700" fill="{color}">{m}</text>')
