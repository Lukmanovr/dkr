# ═════════════════════════════ pattern cheat sheet ═════════════════════════
# verified against RotatE (ICLR 2019) Table 1 + the standard 1-to-N analysis
PATTERNS = [
    ("symmetry", "r(a,b) ⇒ r(b,a)", [("✗", "forces r = 0"), ("✓", "built-in"), ("✓", "r real"), ("✓", "rᵢ = ±1")]),
    ("antisymmetry", "r(a,b) ⇒ ¬r(b,a)", [("✓", ""), ("✗", "can't — ever"), ("✓", ""), ("✓", "")]),
    ("inversion", "r₂ = r₁⁻¹", [("✓", "r₂ = −r₁"), ("✗", ""), ("✓", "r₂ = r̄₁"), ("✓", "r₂ = r₁⁻¹")]),
    ("composition", "r₃ = r₂ ∘ r₁", [("✓", "r₃ = r₁+r₂"), ("✗", ""), ("✗", ""), ("✓", "r₃ = r₁∘r₂")]),
    ("1-to-N", "one head, many tails", [("✗", "tails collapse"), ("✓", ""), ("✓", ""), ("✗", "bijective")]),
]
MODELS = [("TransE", "var(--dkr-accent, #d9603b)"), ("DistMult", "#7c5cd6"),
          ("ComplEx", "var(--dkr-blue, #0f8377)"), ("RotatE", "var(--dkr-green, #199473)")]

pat = [f'  <text x="380" y="24" text-anchor="middle" font-family="{SANS}" font-size="13" fill="var(--dkr-muted, #6e6e7a)">what each scoring geometry can represent exactly — the model-selection cheat sheet</text>']
