# ═══════════════ claim 3: CSL(11,2) vs CSL(11,3) ═══════════════════════════
def csl(n, s):
    g = nx.Graph()
    for v in range(n):
        g.add_edge(v, (v + 1) % n)
        g.add_edge(v, (v + s) % n)
    return g


C2, C3s = csl(11, 2), csl(11, 3)
assert all(d == 4 for _, d in C2.degree()) and all(d == 4 for _, d in C3s.degree())
_, hc2 = wl_colors(C2)
_, hc3 = wl_colors(C3s)
assert hc2[-1] == hc3[-1] == [11], "vertex-transitive: WL never splits either graph"
assert not nx.is_isomorphic(C2, C3s), "CSL(11,2) and CSL(11,3) are non-isomorphic"

# RW return probabilities separate them (and are constant within each graph)
def rw_returns(G, kmax=6):
    A = nx.to_numpy_array(G)
    M = A / A.sum(1, keepdims=True)
    out = []
    P = np.eye(len(A))
    for _ in range(kmax):
        P = P @ M
        out.append(np.diag(P).copy())
    return np.array(out)   # (kmax, n)


r2, r3 = rw_returns(C2), rw_returns(C3s)
assert np.allclose(r2, r2[:, :1], atol=1e-12) and np.allclose(r3, r3[:, :1], atol=1e-12), \
    "vertex-transitivity: return probs constant within each graph"
gap = np.abs(r2[:, 0] - r3[:, 0]).max()
assert gap > 0.01, f"return-probability signatures must differ between the graphs (gap {gap})"
k_best = int(np.argmax(np.abs(r2[:, 0] - r3[:, 0])))
print(f"CSL verified: both 4-regular, WL-blind, non-isomorphic; RWPE gap {gap:.4f} (max at k={k_best + 1})"
      f" — CSL(11,2) k4 return {r2[3, 0]:.4f} vs CSL(11,3) {r3[3, 0]:.4f}")

# ═══════════════ claim 4: barbell sensitivity + one-edge rescue ════════════
def ahat(G):
    A = nx.to_numpy_array(G, weight=None)
    At = A + np.eye(len(A))
    d = At.sum(1)
    Dm = np.diag(d ** -0.5)
    return Dm @ At @ Dm


BAR = nx.barbell_graph(5, 2)          # K5 — path of 2 — K5, nodes 0..11
SRC, FAR = 0, 11                      # source in left clique, target deep right (distance 5)
K = 5                                 # just deep enough to REACH the far clique — squashed, not merely absent
S = np.linalg.matrix_power(ahat(BAR), K)
sens_near = S[SRC, 4]                 # node 4 = left clique's bridgehead
sens_far = S[SRC, FAR]
ratio = sens_near / sens_far
assert 0 < sens_far < 1e-2 and ratio > 50, f"bridge crush: near {sens_near:.4f}, far {sens_far:.6f}, ratio {ratio:.0f}"

BAR2 = BAR.copy()
BAR2.add_edge(1, 10)                  # ONE rewiring edge across
S2 = np.linalg.matrix_power(ahat(BAR2), K)
rescue = S2[SRC, FAR] / sens_far
assert rescue > 20, f"one added edge must lift far sensitivity by >20x (got {rescue:.0f}x)"
print(f"barbell verified (K={K}): near {sens_near:.4f}, across-bridge {sens_far:.2e} "
      f"(ratio {ratio:.0f}x); one rewiring edge lifts it {rescue:.0f}x to {S2[SRC, FAR]:.2e}")


