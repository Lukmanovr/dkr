def draw_tree(cx, top, depth, spread, r=9):
    """Full binary computation tree (every node has 2 neighbors) to `depth`."""
    parts, pos = [], {(): (cx, top)}
    for d in range(1, depth + 1):
        step = spread / (2 ** d)
        for key in [k for k in pos if len(k) == d - 1]:
            x0, y0 = pos[key]
            for i, dx in enumerate((-step, step)):
                child = key + (i,)
                pos[child] = (x0 + dx, y0 + 56)
                parts.append(f'  <line x1="{x0:.1f}" y1="{y0}" x2="{pos[child][0]:.1f}" '
                             f'y2="{pos[child][1]}" stroke="var(--dkr-muted, #8e8e9a)" stroke-width="1.4"/>')
    for key, (x, y) in pos.items():
        col = "var(--dkr-accent, #d9603b)" if key == () else "var(--dkr-blue, #0f8377)"
        parts.append(f'  <circle cx="{x:.1f}" cy="{y}" r="{r if key == () else (7 if len(key) < 3 else 5.5)}" fill="{col}"/>')
    return parts


