def wl_colors(G, rounds=None, init=None):
    """Run WL to stability (or a fixed number of rounds); return final colors
    canonicalized to small ints, and the per-round histograms."""
    colors = {v: (0 if init is None else init[v]) for v in G}
    hists = []
    r = 0
    while True:
        new = {v: (colors[v], tuple(sorted(colors[u] for u in G[v]))) for v in G}
        canon = {sig: i for i, sig in enumerate(sorted(set(new.values())))}
        new = {v: canon[new[v]] for v in G}
        hists.append(sorted(Counter(new.values()).values()))
        r += 1
        if new == colors or (rounds and r >= rounds):
            colors = new
            break
        colors = new
    return colors, hists


